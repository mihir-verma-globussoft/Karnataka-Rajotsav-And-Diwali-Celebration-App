// Generates lib/features/rajyotsava/data/karnataka_places.dart from
// docs/data/karnataka_famous_places_google_maps.csv.
//
// Run from the repository root after editing the CSV:
//   dart run tool/generate_rajyotsava_places.dart
//
// The CSV has three columns: District, Place, Google Maps (a
// google.com/maps/search link whose `query` is the maps destination). Fields
// must not contain commas or double quotes.
// ignore_for_file: avoid_print

import 'dart:io';

const _csvPath = 'docs/data/karnataka_famous_places_google_maps.csv';
const _outPath = 'lib/features/rajyotsava/data/karnataka_places.dart';

/// CSV district names that differ from the app's district ids.
const _districtIds = {
  'Bengaluru South (Ramanagara)': 'ramanagara',
  'Chikkaballapura': 'chikkaballapur',
};

String _id(String district) =>
    _districtIds[district] ??
    district.toLowerCase().replaceAll(RegExp('[^a-z]+'), '_');

String _quote(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";

void main() {
  final lines = File(_csvPath)
      .readAsStringSync()
      .replaceFirst(String.fromCharCode(0xFEFF), '')
      .split(RegExp(r'\r?\n'))
      .where((l) => l.trim().isNotEmpty)
      .toList();
  if (lines.first.trim() != 'District,Place,Google Maps') {
    stderr.writeln('Unexpected header: ${lines.first}');
    exit(1);
  }

  final byDistrict = <String, List<(String, String)>>{};
  for (final line in lines.skip(1)) {
    final cells = line.split(',');
    if (cells.length != 3) {
      stderr.writeln('Expected 3 columns: $line');
      exit(1);
    }
    final [district, place, link] = cells;
    final query = Uri.parse(link.trim()).queryParameters['query'];
    if (query == null || query.isEmpty) {
      stderr.writeln('Link has no query: $line');
      exit(1);
    }
    byDistrict.putIfAbsent(_id(district.trim()), () => []).add((
      place.trim(),
      query,
    ));
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_rajyotsava_places.dart from')
    ..writeln('// docs/data/karnataka_famous_places_google_maps.csv.')
    ..writeln('// Do not edit by hand: edit the CSV and run the tool again.')
    ..writeln()
    ..writeln("import '../domain/models.dart';")
    ..writeln()
    ..writeln('/// Famous places to visit, by district id.')
    ..writeln('const Map<String, List<FamousPlace>> karnatakaPlaces = {');
  for (final MapEntry(key: id, value: places) in byDistrict.entries) {
    out.writeln('  ${_quote(id)}: [');
    for (final (name, query) in places) {
      out.writeln(
        '    FamousPlace(name: ${_quote(name)}, mapQuery: ${_quote(query)}),',
      );
    }
    out.writeln('  ],');
  }
  out.writeln('};');
  File(_outPath).writeAsStringSync(out.toString());
  // Keep the output in the repository's format (scripts/check.sh checks it).
  final format = Process.runSync('dart', ['format', _outPath]);
  if (format.exitCode != 0) {
    stderr.writeln(format.stderr);
    exit(1);
  }
  print(
    'Wrote ${byDistrict.values.fold(0, (n, p) => n + p.length)} places in '
    '${byDistrict.length} districts to $_outPath',
  );
}
