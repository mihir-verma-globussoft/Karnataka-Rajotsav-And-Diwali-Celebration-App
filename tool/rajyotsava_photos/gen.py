"""Resize downloaded photos into the app and generate data/rajyotsava_photos.dart."""
import html, json, os, re, shutil, subprocess, sys
REPO = sys.argv[1]
OUT_DART = os.path.join(REPO, 'lib/features/rajyotsava/data/rajyotsava_photos.dart')
def clean(s):
    s = re.sub(r'<[^>]+>', '', s or '')
    return re.sub(r'\s+', ' ', html.unescape(s)).strip() or 'Unknown'
def slug(s): return re.sub(r'[^a-z0-9]+', '_', s.lower()).strip('_')
def esc(s): return s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
groups = []  # (folder, map name, {key: (src_path, credit)}, max_px)
def load(dl, folder, mapname, px, keyfn=lambda k: k):
    c = json.load(open(os.path.join(dl, '_credits.json')))
    items = {}
    for k, cred in c.items():
        src = os.path.join(dl, slug(k) + '.jpg') if os.path.exists(os.path.join(dl, slug(k) + '.jpg')) else os.path.join(dl, k + '.jpg')
        if os.path.exists(src): items[keyfn(k)] = (src, cred, slug(k))
    groups.append((folder, mapname, items, px))
load('dl_stars', 'stars', 'starPhotos', 360)
load('dl_discover', 'discover', 'discoverPhotos', 640)
if os.path.exists('dl_places/_credits.json'):
    load('dl_places', 'places', 'placePhotos', 240)
else:
    groups.append(('places', 'placePhotos', {}, 360))
lines = ['// GENERATED by tool/rajyotsava_photos/gen.py from Wikimedia Commons.',
         '// Do not edit by hand. Every photo is freely licensed; credits are',
         '// shown on the Photo credits screen.', '',
         "import '../domain/models.dart';", '']
all_credits = []
for folder, mapname, items, px in groups:
    dest = os.path.join(REPO, 'assets/images', folder)
    if os.path.exists(dest): shutil.rmtree(dest)
    os.makedirs(dest)
    # Keeps the folder in git even when empty (pubspec lists it).
    open(os.path.join(dest, '.keep'), 'w').close()
    lines.append(f'const Map<String, String> {mapname} = {{')
    for key in sorted(items):
        src, cred, fname = items[key]
        asset = f'assets/images/{folder}/{fname}.jpg'
        subprocess.run(['sips', '-Z', str(px), '-s', 'format', 'jpeg', '-s', 'formatOptions', '72', src, '--out', os.path.join(REPO, asset)], check=True, capture_output=True)
        lines.append(f"  '{esc(key)}': '{asset}',")
        all_credits.append((asset, cred))
    lines.append('};'); lines.append('')
lines.append('/// Credit for every bundled photo, by asset path.')
lines.append('const Map<String, PhotoCredit> photoCredits = {')
for asset, cred in all_credits:
    title = cred['file'].rsplit('.', 1)[0].replace('_', ' ')
    lines.append(f"  '{asset}': PhotoCredit(")
    lines.append(f"    title: '{esc(title)}',")
    lines.append(f"    author: '{esc(clean(cred['artist']))}',")
    lines.append(f"    license: '{esc(cred['license'])}',")
    lines.append(f"    source: '{esc(cred['page'])}',")
    lines.append('  ),')
lines.append('};')
open(OUT_DART, 'w').write('\n'.join(lines) + '\n')
subprocess.run(['dart', 'format', OUT_DART], check=True, capture_output=True)
print('photos:', len(all_credits))
